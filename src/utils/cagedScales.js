/**
 * 把靜態資料列轉成原本程式使用的 note 物件。
 * 這不是音階自動生成器；notes 與 path 都已經在 CAGED_SCALES 裡手動列出。
 */
function makeStaticScaleShape(
  id,
  name,
  modeKey,
  formName,
  rootString,
  noteRows,
  path
) {
  return {
    id,
    name,
    modeKey,
    formName,
    rootString,
    notes: noteRows.map(([
      noteId,
      string,
      offset,
      interval,
      semitoneFromRoot,
      relativePitchScore
    ]) => ({
      id: noteId,
      string,
      offset,
      interval,
      semitoneFromRoot,
      relativePitchScore
    })),
    path
  };
}

